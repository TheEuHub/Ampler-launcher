#!/usr/bin/env python3
"""
Ampler Launcher - Unified HTTP/HTTPS Local & Preview Server.

- Serves app/ (the document root: index.html + assets/) over HTTP,
  default 0.0.0.0:8080.
- Sends COOP (same-origin) + COEP (credentialless / require-corp) headers so
  SharedArrayBuffer and WASM-GC Eaglercraft builds run at full speed while
  allowing HTTPS fonts/APIs/CDNs.
- Dynamically serves /assets/skins/list.js matching tools/bake-skins.py.
- Serves recovered clients from app/mc/ without substituting unrelated builds.
"""

import argparse
import functools
import http.server
import json
import os
import shutil
import socket
import socketserver
import subprocess
import sys
from pathlib import Path


def _find_root():
    """The document root: the folder holding index.html and assets/.

    tools/serve.py lives one level above app/, so the usual answer is
    <repo>/app. Walking up keeps the script working when it is copied next to
    an index.html (the old layout).
    """
    d = os.path.dirname(os.path.abspath(__file__))
    while True:
        for candidate in (d, os.path.join(d, "app")):
            if (os.path.isfile(os.path.join(candidate, "index.html"))
                    and os.path.isdir(os.path.join(candidate, "assets"))):
                return candidate
        parent = os.path.dirname(d)
        if parent == d:
            break
        d = parent
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


ROOT = _find_root()
ROOT_PATH = Path(ROOT)
REPO = ROOT_PATH.parent
# Clients recovered by tools/recover_*.py live in app/mc/ (served); .cache/mc/
# is scratch space outside the document root.
CACHE_MC = REPO / ".cache" / "mc"

SKINS_DIR = os.path.join(ROOT, "assets", "skins")
SKINS_LIST_PATH = "/assets/skins/list.js"
SKINS_LIST_FILE = os.path.join(SKINS_DIR, "list.js")
SKIN_IMAGE_EXTS = (".png", ".jpg", ".jpeg", ".webp", ".gif")


def skin_folders():
    """Every folder in assets/skins/ that holds at least one image."""
    names = []
    try:
        for name in sorted(os.listdir(SKINS_DIR)):
            if name.startswith("."):
                continue
            folder = os.path.join(SKINS_DIR, name)
            if not os.path.isdir(folder):
                continue
            try:
                files = os.listdir(folder)
            except OSError:
                continue
            if any(f.lower().endswith(SKIN_IMAGE_EXTS) for f in files):
                names.append(name)
    except OSError:
        pass
    return names


def skins_list_js():
    """window.AMPLER_SKINS_FROM_DIR = [folders that look like skins]."""
    return ("/* generated by tools/serve.py from the folders in\n"
            "   assets/skins/ - edit the folders, not this file. */\n"
            "window.AMPLER_SKINS_FROM_DIR = %s;\n"
            % json.dumps(skin_folders(), ensure_ascii=False))


def _find_case_insensitive(base_dir: Path, name: str) -> Path | None:
    if not base_dir.is_dir():
        return None
    exact = base_dir / name
    if exact.exists():
        return exact
    low = name.lower()
    try:
        for child in base_dir.iterdir():
            if child.name.lower() == low:
                return child
    except OSError:
        pass
    return None


def try_materialize_mc_folder(folder_name: str) -> Path | None:
    direct = _find_case_insensitive(ROOT_PATH / "mc", folder_name)
    if direct and (direct / "index.html").is_file():
        return direct
    cached = _find_case_insensitive(CACHE_MC, folder_name)
    if cached and (cached / "index.html").is_file():
        return cached

    target_cache = CACHE_MC / folder_name
    candidate_repos = [
        Path("/tmp/repos/theveil-media_AmplerLauncher"),
        Path("/tmp/repos/Dev-subha-stack_minecraft-launcher"),
        Path("/tmp/repos/gtrdhf_AmplerLauncher"),
    ]
    for repo in candidate_repos:
        if not (repo / ".git").exists():
            continue
        try:
            subprocess.run(
                ["git", "sparse-checkout", "add", f"mc/{folder_name}"],
                cwd=str(repo),
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=30,
                check=False,
            )
            subprocess.run(
                ["git", "checkout", "HEAD"],
                cwd=str(repo),
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=60,
                check=False,
            )
            src_dir = _find_case_insensitive(repo / "mc", folder_name)
            if src_dir and (src_dir / "index.html").is_file():
                target_cache.parent.mkdir(parents=True, exist_ok=True)
                shutil.copytree(src_dir, target_cache, dirs_exist_ok=True)
                return target_cache
        except Exception:
            pass
    return None


EXTRA_MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".woff2": "font/woff2",
    ".woff": "font/woff",
    ".epk": "application/octet-stream",
    ".epw": "application/octet-stream",
    ".wasm": "application/wasm",
    ".map": "application/json; charset=utf-8",
    ".svg": "image/svg+xml",
}


class Handler(http.server.SimpleHTTPRequestHandler):
    """Static file handler with isolation headers and a dynamic skins list."""

    isolation = True
    server_version = "AmplerOffline/2.4"

    def end_headers(self):
        if self.isolation:
            self.send_header("Cross-Origin-Opener-Policy", "same-origin")
            self.send_header("Cross-Origin-Embedder-Policy", "credentialless")
            self.send_header("Cross-Origin-Resource-Policy", "cross-origin")
        self.send_header("Cache-Control", "no-cache")
        super().end_headers()

    def _send_skins_list(self, include_body=True):
        body = skins_list_js().encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "text/javascript; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        if include_body:
            self.wfile.write(body)

    def do_GET(self):
        if self.path.split("?")[0] == SKINS_LIST_PATH:
            self._send_skins_list()
            return
        super().do_GET()

    def do_HEAD(self):
        if self.path.split("?")[0] == SKINS_LIST_PATH:
            self._send_skins_list(include_body=False)
            return
        super().do_HEAD()

    def guess_type(self, path):
        ext = os.path.splitext(path)[1].lower()
        return EXTRA_MIME.get(ext, super().guess_type(path))

    def log_message(self, fmt, *args):
        sys.stdout.write("  %s\n" % (fmt % args))
        sys.stdout.flush()


class Server(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True


def local_ip():
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        s.connect(("10.255.255.255", 1))
        return s.getsockname()[0]
    except OSError:
        return "127.0.0.1"
    finally:
        s.close()


def main():
    parser = argparse.ArgumentParser(description="Serve the Ampler Launcher.")
    parser.add_argument("--port", type=int, default=8080)
    parser.add_argument("--host", default="0.0.0.0")
    parser.add_argument("--no-isolation", action="store_true",
                        help="do not send COOP/COEP (disables SharedArrayBuffer)")
    parser.add_argument("--no-browser", action="store_true",
                        help="do not try to open a browser window")
    parser.add_argument("--no-open", action="store_true",
                        help="alias for --no-browser")
    args = parser.parse_args()

    Handler.isolation = not args.no_isolation
    handler = functools.partial(Handler, directory=ROOT)

    try:
        httpd = Server((args.host, args.port), handler)
    except OSError as exc:
        print("Could not bind %s:%d - %s" % (args.host, args.port, exc))
        return 1

    print("=" * 62)
    print(" Ampler Launcher - server")
    print("=" * 62)
    print("  Repo         : %s" % REPO)
    print("  Document root: %s" % ROOT)
    print("  Launcher     : http://localhost:%d/" % args.port)
    print("  From another device on your LAN:")
    print("                 http://%s:%d/" % (local_ip(), args.port))
    print("  Isolation hdrs: %s" % ("ON (SharedArrayBuffer enabled)"
                                      if Handler.isolation else "OFF"))
    print("  Skins          : %d folder(s) in assets/skins/ (scanned live)"
          % len(skin_folders()))
    print("  Press Ctrl+C to stop.")
    print("=" * 62)
    sys.stdout.flush()

    if not (args.no_browser or args.no_open):
        try:
            import webbrowser
            webbrowser.open("http://localhost:%d/" % args.port)
        except Exception:
            pass

    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        print("\nStopped.")
    finally:
        httpd.server_close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
